'use strict';

(function initRoadmapEvaluationCore(root, factory) {
  const api = factory(root);
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  if (root) root.EnergyRoadmapEvaluationCore = Object.freeze(api);
})(typeof window !== 'undefined' ? window : globalThis, function roadmapEvaluationFactory(root) {
  const MODEL_VERSION = 'roadmap-evaluation-v0.1';
  const ENVELOPE_CARD_BY_DEFINITION = Object.freeze({
    wall: 'envelope-wall',
    'top-ceiling': 'envelope-roof',
    roof: 'envelope-roof',
    basement: 'envelope-basement',
    'ground-floor': 'envelope-basement',
    windows: 'envelope-windows',
    doors: 'envelope-windows',
  });

  function finite(value, fallback = null) {
    if (value === '' || value === null || value === undefined) return fallback;
    const number = Number(value);
    return Number.isFinite(number) ? number : fallback;
  }

  function fieldValue(value, fallback = null) {
    if (value && typeof value === 'object' && value.__type === 'energy-tools-field') return value.value ?? fallback;
    return value ?? fallback;
  }

  function getPath(object, path, fallback = null) {
    let cursor = object;
    for (const key of String(path).split('.').filter(Boolean)) {
      if (cursor === null || cursor === undefined) return fallback;
      cursor = cursor[key];
    }
    return fieldValue(cursor, fallback);
  }

  function orderedStages(roadmap) {
    return Object.values(roadmap?.stages ?? {}).sort((a, b) => Number(a.order ?? 0) - Number(b.order ?? 0));
  }

  function itemsForStage(roadmap, stageId) {
    return Object.values(roadmap?.items ?? {})
      .filter((item) => item.stageId === stageId)
      .sort((a, b) => Number(a.order ?? 999999) - Number(b.order ?? 999999));
  }

  function costModel(configs, id) {
    return (configs.renovationCosts?.models ?? []).find((item) => item.id === id && item.active !== false) ?? null;
  }

  function lifetimeFor(configs, id) {
    return (configs.componentLifetimes?.items ?? []).find((item) => item.cost_model_id === id && item.active !== false) ?? null;
  }

  function referenceConditionState(configs, id) {
    const states = configs.referenceConditions?.states ?? [];
    return states.find((item) => item.id === id)
      ?? states.find((item) => item.id === configs.referenceConditions?.default)
      ?? { id: 'age_appropriate', label: 'altersgerecht', horizon_factor: 1, reference_cost_key: 'middle' };
  }

  function storedMeasure(project, definition) {
    const measures = Object.values(project?.measures ?? {}).filter((item) => item && item.status !== 'archived' && item.componentId === definition.componentId && item.thermalEnvelope?.relevant !== false);
    return measures.find((item) => item.autoGenerated !== true)
      ?? measures.find((item) => item.proposalProfile === 'recommended')
      ?? measures[0]
      ?? null;
  }

  function targetForDefinition(project, definition, configs, adapter) {
    const stored = storedMeasure(project, definition);
    const storedU = finite(stored?.selectedVariant?.uValue, null);
    if (storedU > 0) return { value: storedU, source: stored.autoGenerated ? 'Bauteil & Sanierung · Empfehlung' : 'Bauteil & Sanierung · gewählte Maßnahme', stored };
    const target = finite(configs.envelopeTargets?.components?.[definition.dataId]?.recommended, null);
    if (target > 0) return { value: target, source: 'zentraler Hüll-Zielwert', stored };
    const existing = adapter.constructionUValue(project, definition, configs.existingUValuesConfig);
    return { value: existing.value, source: existing.source, stored };
  }

  function activeEnvelopeCandidates(project, activeCardIds, configs, deps) {
    const adapter = deps.projectEnergyAdapter;
    const definitions = adapter.DEFAULT_ENVELOPE_DEFINITIONS;
    return definitions
      .filter((definition) => activeCardIds.has(ENVELOPE_CARD_BY_DEFINITION[definition.id]))
      .filter((definition) => adapter.componentEnvelopeRelevant(project, definition))
      .map((definition) => {
        const existing = adapter.constructionUValue(project, definition, configs.existingUValuesConfig);
        const target = targetForDefinition(project, definition, configs, adapter);
        return {
          id: definition.id,
          componentId: definition.componentId,
          cardId: ENVELOPE_CARD_BY_DEFINITION[definition.id],
          existingUValue: existing.value,
          targetUValue: target.value,
          energySavingsManual: false,
          source: target.source,
        };
      })
      .filter((item) => finite(item.existingUValue, null) > 0 && finite(item.targetUValue, null) > 0);
  }

  function emissionFactor(configs, carrierId) {
    return finite((configs.emissionFactors?.items ?? []).find((item) => item.id === carrierId && item.active !== false)?.factor_kg_co2e_kwh, null);
  }

  function energyEvaluation(project, roadmap, cardsData, configs, deps) {
    const stages = orderedStages(roadmap);
    const annualEnergy = Math.max(0, finite(getPath(project, 'consumption.heating.annualEnergy', null), 0));
    const carrierId = getPath(project, 'systems.heating.energyCarrier', null);
    const baseFactor = emissionFactor(configs, carrierId);
    const envelopeDefinitions = deps.projectEnergyAdapter.DEFAULT_ENVELOPE_DEFINITIONS;
    const heatingResult = project?.economics?.latestCalculation?.measureResults?.heating ?? null;
    const heatingTargetEfficiency = finite(heatingResult?.targetEfficiency, null);
    const heatingTargetCarrier = heatingResult?.targetCarrierId ?? null;
    let previousSavings = 0;
    let previousCo2Savings = 0;
    const cumulativeCards = new Set();
    const rows = [];

    for (const stage of stages) {
      const stageItems = itemsForStage(roadmap, stage.id);
      stageItems.forEach((item) => cumulativeCards.add(item.cardId));
      const candidates = activeEnvelopeCandidates(project, cumulativeCards, configs, deps);
      let impact = null;
      try {
        impact = annualEnergy > 0
          ? deps.projectEnergyAdapter.anchoredImpact(project, envelopeDefinitions, candidates, {
            energyFlowDefaults: configs.energyFlowDefaults,
            existingUValuesConfig: configs.existingUValuesConfig,
            hgtFallbackKd: 3500,
          }, deps.anchorCore)
          : null;
      } catch (error) {
        impact = null;
      }

      const baseEfficiency = Math.max(0.01, finite(impact?.base?.inputs?.usefulHeatFactor, getPath(project, 'systems.heating.usefulHeatFactor', 0.85)));
      const roomHeatAfterUseful = finite(impact?.realRoomAfterKwh, null);
      const hotWaterUseful = Math.max(0, finite(impact?.base?.losses?.hotWaterKwh, 0));
      const usefulAfter = roomHeatAfterUseful !== null ? Math.max(0, roomHeatAfterUseful + hotWaterUseful) : null;
      const heatingActive = cumulativeCards.has('heating-replacement') && heatingTargetEfficiency > 0 && heatingTargetCarrier;
      let candidateEnergy = annualEnergy;
      if (impact?.available) candidateEnergy = Math.max(0, annualEnergy - Math.max(0, finite(impact.deliveredSavingsKwh, 0)));
      if (heatingActive && usefulAfter !== null) candidateEnergy = Math.max(0, usefulAfter / heatingTargetEfficiency);

      const cumulativeSavings = annualEnergy > 0 ? annualEnergy - candidateEnergy : 0;
      const incrementalSavings = cumulativeSavings - previousSavings;
      const candidateCarrier = heatingActive ? heatingTargetCarrier : carrierId;
      const candidateFactor = emissionFactor(configs, candidateCarrier);
      const baseCo2 = baseFactor !== null ? annualEnergy * baseFactor : null;
      const candidateCo2 = candidateFactor !== null ? candidateEnergy * candidateFactor : null;
      const cumulativeCo2Savings = baseCo2 !== null && candidateCo2 !== null ? baseCo2 - candidateCo2 : null;
      const incrementalCo2Savings = cumulativeCo2Savings !== null ? cumulativeCo2Savings - previousCo2Savings : null;

      const stageEnergyCards = stageItems.map((item) => cardsData.cardMap?.get(item.cardId)).filter((card) => card?.energyRelevant && card?.type === 'measure');
      const modeledStageCards = new Set(candidates.filter((candidate) => stageItems.some((item) => item.cardId === candidate.cardId)).map((candidate) => candidate.cardId));
      if (heatingActive && stageItems.some((item) => item.cardId === 'heating-replacement')) modeledStageCards.add('heating-replacement');
      const unmodeled = stageEnergyCards.filter((card) => !modeledStageCards.has(card.id)).map((card) => card.title);
      const hasModeledStageChange = modeledStageCards.size > 0;
      rows.push({
        stageId: stage.id,
        available: Boolean(impact?.available && hasModeledStageChange),
        baseAvailable: Boolean(impact?.available),
        annualEnergyBeforeKwh: annualEnergy || null,
        savingsKwh: hasModeledStageChange ? incrementalSavings : 0,
        savingsPercent: annualEnergy > 0 && hasModeledStageChange ? incrementalSavings / annualEnergy * 100 : null,
        cumulativeSavingsKwh: cumulativeSavings,
        cumulativeEnergyAfterKwh: annualEnergy > 0 ? candidateEnergy : null,
        co2SavingsKg: hasModeledStageChange ? incrementalCo2Savings : null,
        cumulativeCo2SavingsKg: cumulativeCo2Savings,
        carrierId,
        candidateCarrierId: candidateCarrier,
        emissionFactorKgKwh: baseFactor,
        partial: unmodeled.length > 0,
        unmodeledCards: unmodeled,
        heatingSystemLabel: heatingActive ? (heatingResult?.systemLabel ?? 'Ziel-Heizsystem') : null,
        climateSource: impact?.base?.plausibility?.source ?? null,
        hwbDeviationPercent: finite(impact?.hwbDeviationPercent, null),
      });
      previousSavings = cumulativeSavings;
      previousCo2Savings = cumulativeCo2Savings ?? previousCo2Savings;
    }

    return {
      available: rows.some((row) => row.available),
      annualEnergyKwh: annualEnergy || null,
      carrierId,
      rows,
      cumulativeSavingsKwh: rows.at(-1)?.cumulativeSavingsKwh ?? 0,
      cumulativeEnergyAfterKwh: rows.at(-1)?.cumulativeEnergyAfterKwh ?? (annualEnergy || null),
      cumulativeCo2SavingsKg: rows.at(-1)?.cumulativeCo2SavingsKg ?? null,
      note: 'Etappen werden kumulativ neu gerechnet; Einzelersparnisse werden nicht addiert. Die Hüllwirkung wird verbrauchsverankert berechnet. Ein Heizungstausch wird quantitativ einbezogen, sobald das Wirtschaftlichkeitstool ein konkretes Zielsystem im gemeinsamen Ergebnis hinterlegt hat.',
    };
  }

  function fallbackInvestment(project, definition, configs, deps) {
    const adapter = deps.projectEnergyAdapter;
    const model = costModel(configs, definition.costModelId);
    if (!model) return { value: null, source: null };
    const area = Math.max(0, finite(getPath(project, definition.areaPath, 0), 0));
    if (!(area > 0)) return { value: null, source: null };

    if (definition.kind === 'exchange') {
      const middle = finite(model.range_eur_m2?.middle, finite(model.base_cost_eur_m2, null));
      return middle > 0 ? { value: area * middle, source: 'zentraler Richtkostenwert' } : { value: null, source: null };
    }
    if (definition.kind === 'door') return { value: null, source: null };

    const existing = adapter.constructionUValue(project, definition, configs.existingUValuesConfig).value;
    const target = targetForDefinition(project, definition, configs, adapter).value;
    if (!(existing > 0) || !(target > 0) || !deps.measureCore?.requiredThicknessCm || !deps.measureCore?.investmentForThickness) return { value: null, source: null };
    const raw = deps.measureCore.requiredThicknessCm(existing, target, 0.035);
    const thickness = raw === null ? null : deps.measureCore.ceilToStep(raw, 2);
    if (thickness === null) return { value: null, source: null };
    const investment = deps.measureCore.investmentForThickness({
      thicknessCm: thickness,
      areaM2: area,
      baseCostEurM2: finite(model.base_cost_eur_m2, 0),
      variableCostEurM2Cm: finite(model.variable_cost_eur_m2_cm, 0),
      sunkCostEurM2: finite(model.sunk_cost_eur_m2, 0),
      renewalContext: 'renewal_due',
    });
    return { value: Math.max(0, finite(investment.fullInvestmentEur, 0)), source: 'zentraler Richtkostenwert' };
  }

  function referenceCost(project, definition, configs, fullInvestmentEur) {
    const draft = project?.modules?.wirtschaftlichkeit?.measureDrafts?.[definition.id] ?? {};
    if (draft.referenceCostManual && finite(draft.referenceCostEur, null) !== null) {
      return { value: Math.max(0, finite(draft.referenceCostEur, 0)), known: true, source: 'manuell / Wirtschaftlichkeit' };
    }
    const model = costModel(configs, definition.costModelId);
    const reference = model?.reference ?? null;
    const mode = reference?.mode ?? 'none';
    if (mode === 'none') return { value: 0, known: true, source: 'keine reguläre Referenz-Erneuerung', mode };
    if (mode === 'project_specific') return { value: 0, known: false, source: 'projektspezifisch zu klären', mode };

    const condition = referenceConditionState(configs, draft.referenceCondition ?? configs.referenceConditions?.default);
    const key = condition.reference_cost_key ?? 'middle';
    const rate = finite(reference?.range?.[key], finite(reference?.default_cost, finite(model?.sunk_cost_eur_m2, null)));
    const area = Math.max(0, finite(getPath(project, definition.areaPath, 0), 0));
    let value = 0;
    if (definition.kind === 'door') return { value: 0, known: false, source: 'Türanzahl / Umfang offen', mode };
    if (rate !== null && area > 0) value = area * rate;
    return { value: Math.min(Math.max(0, fullInvestmentEur ?? Infinity), Math.max(0, value)), known: rate !== null && area > 0, source: 'zentraler Referenzkostenwert', mode, condition };
  }

  function referenceHorizon(project, definition, configs, deps) {
    const model = costModel(configs, definition.costModelId);
    const draft = project?.modules?.wirtschaftlichkeit?.measureDrafts?.[definition.id] ?? {};
    const referenceMode = model?.reference?.mode ?? 'none';
    if (referenceMode === 'none') return { years: null, source: 'none', basis: 'keine reguläre Referenz-Erneuerung' };
    if (referenceMode === 'project_specific' && !draft.referenceYearConfirmed) return { years: null, source: 'open', basis: 'projektspezifisch zu bestätigen' };
    const lifetime = finite(draft.lifetimeYears, finite(lifetimeFor(configs, definition.costModelId)?.years, null));
    return deps.renewalHorizonCore.calculate({
      currentYear: new Date().getFullYear(),
      explicitOffsetYears: draft.referenceYear,
      explicitConfirmed: Boolean(draft.referenceYearConfirmed),
      lastRenewalYear: draft.lastRenewalYear,
      constructionYear: getPath(project, 'building.profile.constructionYear', null),
      lifetimeYears: lifetime,
      condition: referenceConditionState(configs, draft.referenceCondition ?? configs.referenceConditions?.default),
    });
  }

  function envelopeDefinitionCost(project, definition, configs, deps) {
    if (!deps.projectEnergyAdapter.componentEnvelopeRelevant(project, definition)) return null;
    const draft = project?.modules?.wirtschaftlichkeit?.measureDrafts?.[definition.id] ?? {};
    const stored = storedMeasure(project, definition);
    const snapshotEnvelope = project?.economics?.latestCalculation ?? null;
    const snapshot = snapshotEnvelope?.measureResults?.[definition.id] ?? null;
    const storedNewerThanSnapshot = stored?.updatedAt && snapshotEnvelope?.calculatedAt
      ? new Date(stored.updatedAt).getTime() > new Date(snapshotEnvelope.calculatedAt).getTime()
      : false;
    const snapshotUsable = snapshot && !draft.fullInvestmentManual && !storedNewerThanSnapshot && finite(snapshot.fullInvestmentEur, null) !== null;
    if (snapshotUsable) {
      return {
        known: true,
        definitionId: definition.id,
        label: snapshot.label ?? definition.label,
        fullInvestmentEur: Math.max(0, finite(snapshot.fullInvestmentEur, 0)),
        fundingEur: Math.max(0, finite(snapshot.fundingEur, 0)),
        fundingKnown: finite(snapshot.fundingEur, 0) > 0,
        netInvestmentEur: Math.max(0, finite(snapshot.fullInvestmentEur, 0) - finite(snapshot.fundingEur, 0)),
        referenceCostEur: Math.max(0, finite(snapshot.referenceCostEur, 0)),
        referenceKnown: snapshot.referenceMode === 'none' || finite(snapshot.referenceCostEur, 0) > 0,
        referenceMode: snapshot.referenceMode ?? null,
        referenceSource: 'Wirtschaftlichkeit · letzter gemeinsamer Rechenstand',
        referenceHorizonYears: finite(snapshot.referenceYear, null),
        referenceHorizonSource: finite(snapshot.referenceYear, null) !== null ? 'Wirtschaftlichkeit' : 'open',
        source: 'Wirtschaftlichkeit · letzter gemeinsamer Rechenstand',
      };
    }

    let fullInvestmentEur = null;
    let source = null;
    if (draft.fullInvestmentManual && finite(draft.fullInvestmentEur, null) !== null) {
      fullInvestmentEur = Math.max(0, finite(draft.fullInvestmentEur, 0));
      source = 'manuell / Wirtschaftlichkeit';
    } else if (finite(stored?.costModel?.fullInvestmentEur, null) !== null) {
      fullInvestmentEur = Math.max(0, finite(stored.costModel.fullInvestmentEur, 0));
      source = stored.autoGenerated ? 'Bauteil & Sanierung · Vorschlag' : 'Bauteil & Sanierung';
    } else {
      const fallback = fallbackInvestment(project, definition, configs, deps);
      fullInvestmentEur = fallback.value;
      source = fallback.source;
    }
    if (fullInvestmentEur === null) return { known: false, definitionId: definition.id, label: definition.label };
    const fundingEur = Math.max(0, finite(stored?.funding?.amountEur, 0));
    const fundingKnown = Boolean(stored?.funding?.confirmed || (stored?.funding?.entries ?? []).length);
    const reference = referenceCost(project, definition, configs, fullInvestmentEur);
    const horizon = referenceHorizon(project, definition, configs, deps);
    return {
      known: true,
      definitionId: definition.id,
      label: definition.label,
      fullInvestmentEur,
      fundingEur,
      fundingKnown,
      netInvestmentEur: Math.max(0, fullInvestmentEur - fundingEur),
      referenceCostEur: reference.value,
      referenceKnown: reference.known,
      referenceMode: reference.mode ?? null,
      referenceSource: reference.source,
      referenceHorizonYears: horizon.years,
      referenceHorizonSource: horizon.source,
      source,
    };
  }

  function systemCardCost(project, cardId, configs) {
    const draftId = cardId === 'heating-replacement' ? 'heating' : cardId === 'pv-own-use' ? 'pv' : null;
    if (!draftId) return { known: false };
    const draft = project?.modules?.wirtschaftlichkeit?.measureDrafts?.[draftId] ?? {};
    if (draft.fullInvestmentManual && finite(draft.fullInvestmentEur, null) !== null) {
      return {
        known: true,
        label: cardId === 'heating-replacement' ? 'Heizungstausch' : 'PV',
        fullInvestmentEur: Math.max(0, finite(draft.fullInvestmentEur, 0)),
        fundingEur: 0,
        fundingKnown: false,
        netInvestmentEur: Math.max(0, finite(draft.fullInvestmentEur, 0)),
        referenceCostEur: draft.referenceCostManual ? Math.max(0, finite(draft.referenceCostEur, 0)) : 0,
        referenceKnown: Boolean(draft.referenceCostManual),
        referenceHorizonYears: draft.referenceYearConfirmed ? Math.max(0, finite(draft.referenceYear, 0)) : null,
        source: 'manuell / Wirtschaftlichkeit',
      };
    }
    const snapshot = project?.economics?.latestCalculation?.measureResults?.[draftId] ?? null;
    if (snapshot && finite(snapshot.fullInvestmentEur, null) !== null) {
      return {
        known: true,
        label: snapshot.label ?? (cardId === 'heating-replacement' ? 'Heizungstausch' : 'PV'),
        fullInvestmentEur: Math.max(0, finite(snapshot.fullInvestmentEur, 0)),
        fundingEur: Math.max(0, finite(snapshot.fundingEur, 0)),
        fundingKnown: finite(snapshot.fundingEur, 0) > 0,
        netInvestmentEur: Math.max(0, finite(snapshot.fullInvestmentEur, 0) - finite(snapshot.fundingEur, 0)),
        referenceCostEur: Math.max(0, finite(snapshot.referenceCostEur, 0)),
        referenceKnown: snapshot.referenceMode === 'none' || finite(snapshot.referenceCostEur, 0) > 0,
        referenceHorizonYears: finite(snapshot.referenceYear, null),
        source: 'Wirtschaftlichkeit · letzter gemeinsamer Rechenstand',
        systemLabel: snapshot.systemLabel ?? null,
      };
    }
    return { known: false, reason: cardId === 'heating-replacement' ? 'Ziel-Heizsystem noch konkretisieren' : 'PV-Größe / Kosten noch konkretisieren' };
  }

  function cardCost(project, card, configs, deps) {
    const definitions = deps.projectEnergyAdapter.DEFAULT_ENVELOPE_DEFINITIONS.filter((definition) => ENVELOPE_CARD_BY_DEFINITION[definition.id] === card.id);
    if (definitions.length) {
      const parts = definitions.map((definition) => envelopeDefinitionCost(project, definition, configs, deps)).filter(Boolean);
      const knownParts = parts.filter((part) => part.known);
      if (!knownParts.length) return { cardId: card.id, title: card.title, known: false, parts, reason: 'Kostenbasis noch offen' };
      return {
        cardId: card.id,
        title: card.title,
        known: true,
        partial: knownParts.length < parts.length,
        fullInvestmentEur: knownParts.reduce((sum, part) => sum + part.fullInvestmentEur, 0),
        fundingEur: knownParts.reduce((sum, part) => sum + part.fundingEur, 0),
        fundingKnown: knownParts.some((part) => part.fundingKnown),
        netInvestmentEur: knownParts.reduce((sum, part) => sum + part.netInvestmentEur, 0),
        referenceCostEur: knownParts.reduce((sum, part) => sum + (part.referenceKnown ? part.referenceCostEur : 0), 0),
        referenceKnown: knownParts.some((part) => part.referenceKnown),
        referenceHorizonYears: knownParts.map((part) => finite(part.referenceHorizonYears, null)).filter((value) => value !== null).sort((a, b) => a - b)[0] ?? null,
        parts,
        source: [...new Set(knownParts.map((part) => part.source).filter(Boolean))].join(' + '),
      };
    }
    if (['heating-replacement', 'pv-own-use'].includes(card.id)) return { cardId: card.id, title: card.title, ...systemCardCost(project, card.id, configs) };
    return { cardId: card.id, title: card.title, known: false, reason: 'noch kein quantitativer Kostenadapter' };
  }

  function costEvaluation(project, roadmap, cardsData, configs, deps) {
    const stages = orderedStages(roadmap);
    const rows = stages.map((stage) => {
      const items = itemsForStage(roadmap, stage.id);
      const quantitativeCards = items.map((item) => cardsData.cardMap?.get(item.cardId)).filter((card) => card?.economicsRelevant && card?.type === 'measure');
      const cardRows = quantitativeCards.map((card) => cardCost(project, card, configs, deps));
      const known = cardRows.filter((row) => row.known);
      const fullInvestmentEur = known.reduce((sum, row) => sum + finite(row.fullInvestmentEur, 0), 0);
      const fundingEur = known.reduce((sum, row) => sum + finite(row.fundingEur, 0), 0);
      const referenceCostEur = known.reduce((sum, row) => sum + (row.referenceKnown ? finite(row.referenceCostEur, 0) : 0), 0);
      return {
        stageId: stage.id,
        available: known.length > 0,
        partial: known.length < quantitativeCards.length || known.some((row) => row.partial),
        fullInvestmentEur,
        fundingEur,
        fundingKnown: known.some((row) => row.fundingKnown),
        netInvestmentEur: Math.max(0, fullInvestmentEur - fundingEur),
        referenceCostEur,
        referenceKnown: known.some((row) => row.referenceKnown),
        cardRows,
        unknownCards: cardRows.filter((row) => !row.known).map((row) => row.title),
      };
    });
    return {
      available: rows.some((row) => row.available),
      rows,
      fullInvestmentEur: rows.reduce((sum, row) => sum + row.fullInvestmentEur, 0),
      fundingEur: rows.reduce((sum, row) => sum + row.fundingEur, 0),
      netInvestmentEur: rows.reduce((sum, row) => sum + row.netInvestmentEur, 0),
      referenceCostEur: rows.reduce((sum, row) => sum + row.referenceCostEur, 0),
      partial: rows.some((row) => row.partial),
      note: 'Kosten werden nur dort gezeigt, wo eine gemeinsame oder belastbare Richtkostenbasis vorliegt. Förderung wird je Etappe nur aus konkret zugeordneten Maßnahmen übernommen; paketbezogene Förderung bleibt offen.',
    };
  }

  function evaluate(project, roadmap, cardsData, configs = {}, dependencies = {}) {
    const deps = {
      projectEnergyAdapter: dependencies.projectEnergyAdapter ?? root?.EnergyProjectEnergyAdapter,
      anchorCore: dependencies.anchorCore ?? root?.EnergyConsumptionAnchorCore,
      measureCore: dependencies.measureCore ?? root?.EnvelopeRenovationCore,
      renewalHorizonCore: dependencies.renewalHorizonCore ?? root?.EnergyRenewalHorizonCore,
    };
    if (!deps.projectEnergyAdapter || !deps.anchorCore || !deps.measureCore || !deps.renewalHorizonCore) {
      throw new Error('Sanierungsfahrplan-Auswertung: gemeinsamer Energie-/Maßnahmen-/Erneuerungskern fehlt.');
    }
    const normalizedRoadmap = roadmap ?? project?.roadmap ?? {};
    return {
      modelVersion: MODEL_VERSION,
      calculatedAt: new Date().toISOString(),
      energy: energyEvaluation(project, normalizedRoadmap, cardsData, configs, deps),
      costs: costEvaluation(project, normalizedRoadmap, cardsData, configs, deps),
    };
  }

  return { MODEL_VERSION, ENVELOPE_CARD_BY_DEFINITION, evaluate };
});
